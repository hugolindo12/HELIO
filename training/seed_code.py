def limpar_codigo(texto: str) -> str:
    """Descarta arquivos gerados automaticamente, minificados ou gigantes."""
    if not texto or len(texto) > 60_000 or len(texto) < 200:
        return ""
    linhas = texto.split("\n")
    if max(len(l) for l in linhas) > 300:
        return ""
    cab = texto[:600].lower()
    if "auto-generated" in cab or "autogenerated" in cab or "do not edit" in cab:
        return ""
    return texto


def textos_python(max_chars: int, log: Callable[[str], None] = print) -> Iterator[str]:
    """Código Python público (codeparrot-clean, Hugging Face, streaming). Só onde há internet."""
    from datasets import load_dataset
    ds = load_dataset("codeparrot/codeparrot-clean", split="train", streaming=True)
    total = 0
    for item in ds:
        t = limpar_codigo(item.get("content", ""))
        if not t:
            continue
        total += len(t)
        yield t
        if total >= max_chars:
            log(f"  corpus de código: {total:,} caracteres")
            return


