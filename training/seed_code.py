def cortar_corpo(completacao: str) -> str:
    """Mantém só o corpo da função (linhas indentadas); para no 1º código de nível 0."""
    corpo = []
    for l in completacao.split("\n"):
        if l.strip() and not l.startswith((" ", "\t")):
            break
        corpo.append(l)
    return "\n".join(corpo).rstrip() + "\n"


def executar_teste(codigo: str, teste: str, tempo: int = 5) -> bool:
    with tempfile.NamedTemporaryFile("w", suffix=".py", delete=False, encoding="utf-8") as f:
        f.write(codigo + "\n" + teste + "\n")
        caminho = f.name
    try:
        r = subprocess.run([sys.executable, caminho], capture_output=True, timeout=tempo)
        return r.returncode == 0
    except subprocess.TimeoutExpired:
        return False
    finally:
        Path(caminho).unlink(missing_ok=True)


def completar(modelo, prompt: str, temperatura: float = 1.0, top_k: int = 1,
              max_novos: int = 160) -> str:
    tok = modelo.tokenizer
    ids = [tok.doc] + tok.encode(prompt)
    novos = modelo.gerar(ids[-modelo.cfg.block_size:], max_novos=max_novos, temperatura=temperatura,
                         top_k=top_k, parar_em=(tok.fim, tok.doc))
    return tok.decode(novos)


def avaliar_codigo(modelo, amostras: int = 5, log: Callable[[str], None] = print) -> Dict:
    """pass@1 (greedy), pass@k amostrado e % de código válido — com testes EXECUTADOS."""
    det, ok_greedy, ok_k, validos, total_amostras = [], 0, 0, 0, 0
    for nome, prompt, teste in PROBLEMAS:
        corpo = cortar_corpo(completar(modelo, prompt))
        codigo = prompt + corpo
        try:
            ast.parse(codigo); valido = True
        except SyntaxError:
            valido = False
        passou = valido and executar_teste(codigo, teste)
        algum = passou
        for _ in range(amostras):
            c = prompt + cortar_corpo(completar(modelo, prompt, temperatura=0.8, top_k=40))
            try:
                ast.parse(c); v = True
            except SyntaxError:
                v = False
            validos += v; total_amostras += 1
            if v and not algum and executar_teste(c, teste):
                algum = True
        ok_greedy += passou; ok_k += algum
        det.append({"problema": nome, "passou_greedy": passou, f"passou_em_{amostras + 1}": algum,
                    "valido": valido, "codigo": codigo})
        log(f"  {'✔' if passou else ('~' if algum else '✘')} {nome}")
    n = len(PROBLEMAS)
    return {"problemas": n, "pass@1": round(ok_greedy / n, 3), f"pass@{amostras + 1}": round(ok_k / n, 3),
            "codigo_valido": round(validos / max(1, total_amostras), 3), "detalhes": det}
